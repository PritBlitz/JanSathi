// Downloads the self-hosted fonts (SIL Open Font License) into frontend/fonts/ and writes frontend/css/fonts.css.
// Only the subsets JanSathi needs: Latin for Anton and Noto Sans, the script subset for each Indic Noto family.
// Each @font-face keeps Google's unicode-range, so a browser downloads only the scripts on the page.
// Usage: node tools/fetch-fonts.mjs   (needs network; re-run to update)
import { writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';
const FAMILIES = [
  { family: 'Anton', query: 'Anton', subset: 'latin', file: 'anton-latin' },
  { family: 'Noto Sans', query: 'Noto+Sans:wght@400..800', subset: 'latin', file: 'notosans-latin' },
  { family: 'Noto Sans Devanagari', query: 'Noto+Sans+Devanagari:wght@400..900', subset: 'devanagari', file: 'notosans-devanagari' },
  { family: 'Noto Sans Bengali', query: 'Noto+Sans+Bengali:wght@400..900', subset: 'bengali', file: 'notosans-bengali' },
  { family: 'Noto Sans Tamil', query: 'Noto+Sans+Tamil:wght@400..900', subset: 'tamil', file: 'notosans-tamil' },
  { family: 'Noto Sans Telugu', query: 'Noto+Sans+Telugu:wght@400..900', subset: 'telugu', file: 'notosans-telugu' },
  { family: 'Noto Sans Gujarati', query: 'Noto+Sans+Gujarati:wght@400..900', subset: 'gujarati', file: 'notosans-gujarati' },
  { family: 'Noto Sans Kannada', query: 'Noto+Sans+Kannada:wght@400..900', subset: 'kannada', file: 'notosans-kannada' },
  { family: 'Noto Sans Malayalam', query: 'Noto+Sans+Malayalam:wght@400..900', subset: 'malayalam', file: 'notosans-malayalam' },
  { family: 'Noto Sans Gurmukhi', query: 'Noto+Sans+Gurmukhi:wght@400..900', subset: 'gurmukhi', file: 'notosans-gurmukhi' },
];

mkdirSync(join(root, 'frontend/fonts'), { recursive: true });
let css = '/* Generated by tools/fetch-fonts.mjs. Fonts: SIL Open Font License 1.1, see frontend/fonts/OFL.txt. */\n';
for (const f of FAMILIES) {
  const res = await fetch(`https://fonts.googleapis.com/css2?family=${f.query}&display=swap`, { headers: { 'User-Agent': UA } });
  const text = await res.text();
  const block = text.split('/* ').find((b) => b.startsWith(`${f.subset} */`));
  if (!block) throw new Error(`no ${f.subset} subset for ${f.family}`);
  const url = block.match(/url\((https:[^)]+\.woff2)\)/)[1];
  const weight = block.match(/font-weight: ([^;]+);/)[1];
  const range = block.match(/unicode-range: ([^;]+);/)[1];
  const bytes = Buffer.from(await (await fetch(url, { headers: { 'User-Agent': UA } })).arrayBuffer());
  writeFileSync(join(root, 'frontend/fonts', `${f.file}.woff2`), bytes);
  css += `@font-face{font-family:'${f.family}';font-style:normal;font-weight:${weight};font-display:swap;src:url(../fonts/${f.file}.woff2) format('woff2');unicode-range:${range}}\n`;
  console.log(`${f.file}.woff2  ${(bytes.length / 1024).toFixed(0)} KB`);
}
writeFileSync(join(root, 'frontend/css/fonts.css'), css);
const ofl = await (await fetch('https://raw.githubusercontent.com/google/fonts/main/ofl/notosans/OFL.txt')).text();
writeFileSync(join(root, 'frontend/fonts/OFL.txt'), ofl);
console.log('wrote frontend/css/fonts.css and frontend/fonts/OFL.txt');
